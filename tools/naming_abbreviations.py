"""Regenerate the abbreviation exceptions in .clang-tidy from tools/naming_abbreviations.txt.

clang-tidy's camelBack style rejects names that start with an abbreviation
(MVP, VB, DSVFormat). This writes an IgnoredRegexp for every camelBack kind so
those names are accepted. CamelCase kinds need nothing: they already allow
abbreviations (GetGPUHandle).

Usage:
	python tools/naming_abbreviations.py           # update .clang-tidy
	python tools/naming_abbreviations.py --check   # exit 1 if .clang-tidy is out of date
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ABBREVIATIONS_FILE = ROOT / "tools" / "naming_abbreviations.txt"
CLANG_TIDY_FILE = ROOT / ".clang-tidy"

BEGIN_MARKER = "  # BEGIN generated by tools/naming_abbreviations.py - do not edit by hand"
END_MARKER = "  # END generated"

# Every naming kind configured as camelBack in .clang-tidy.
CAMEL_BACK_KINDS = [
	"Variable",
	"Parameter",
	"LocalVariable",
	"Member",
	"PrivateMember",
	"ProtectedMember",
	"PublicMember",
	"ConstexprVariable",
	"GlobalConstant",
]


def read_abbreviations() -> list[str]:
	abbreviations = []
	for number, line in enumerate(ABBREVIATIONS_FILE.read_text(encoding="utf-8").splitlines(), 1):
		line = line.strip()
		if not line or line.startswith("#"):
			continue
		if not re.fullmatch(r"[A-Z][A-Z0-9]*", line):
			raise ValueError(f"{ABBREVIATIONS_FILE.name}:{number}: '{line}' must be uppercase letters and digits")
		abbreviations.append(line)
	return sorted(set(abbreviations))


def ignored_regexp(abbreviations: list[str]) -> str:
	# Longest first so e.g. RGBA wins over RGB. llvm::Regex is POSIX ERE: no non-capturing groups.
	alternatives = "|".join(sorted(abbreviations, key=lambda a: (-len(a), a)))
	# The abbreviation alone (MVP), plural (GPUs), or followed by a CamelCase word (DSVFormat).
	return f"^({alternatives})(s|[A-Z0-9][a-zA-Z0-9]*)?$"


def generated_block(abbreviations: list[str]) -> list[str]:
	regexp = ignored_regexp(abbreviations)
	lines = [BEGIN_MARKER]
	for kind in CAMEL_BACK_KINDS:
		lines.append(f"  - key: readability-identifier-naming.{kind}IgnoredRegexp")
		lines.append(f"    value: '{regexp}'")
	lines.append(END_MARKER)
	return lines


def updated_config(config: str, abbreviations: list[str]) -> str:
	lines = config.splitlines()
	try:
		begin = lines.index(BEGIN_MARKER)
		end = lines.index(END_MARKER, begin)
	except ValueError:
		raise ValueError(f"{CLANG_TIDY_FILE.name} is missing the generated-section markers:\n{BEGIN_MARKER}\n{END_MARKER}")
	newline = "\r\n" if "\r\n" in config else "\n"
	return newline.join(lines[:begin] + generated_block(abbreviations) + lines[end + 1 :]) + newline


def is_up_to_date() -> bool:
	config = CLANG_TIDY_FILE.read_text(encoding="utf-8")
	return updated_config(config, read_abbreviations()) == config


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--check", action="store_true", help="only check that .clang-tidy is up to date")
	args = parser.parse_args()

	try:
		if args.check:
			if is_up_to_date():
				return 0
			print(".clang-tidy is out of date with tools/naming_abbreviations.txt; run python tools/naming_abbreviations.py", file=sys.stderr)
			return 1

		config = CLANG_TIDY_FILE.read_text(encoding="utf-8")
		updated = updated_config(config, read_abbreviations())
		if updated == config:
			print(".clang-tidy already up to date")
		else:
			CLANG_TIDY_FILE.write_bytes(updated.encode("utf-8"))
			print("updated .clang-tidy")
		return 0
	except ValueError as error:
		print(f"error: {error}", file=sys.stderr)
		return 1


if __name__ == "__main__":
	sys.exit(main())
